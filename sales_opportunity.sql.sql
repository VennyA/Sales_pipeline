SELECT
	DEAL_STAGE,
	COUNT(DEAL_STAGE) AS DEALS
FROM
	SALES_PIPELINE
GROUP BY
	DEAL_STAGE
SELECT
	(
		SUM(
			CASE
				WHEN DEAL_STAGE = 'Won' THEN 1
				ELSE 0
			END
		) * 100.0 / (
			SUM(
				CASE
					WHEN DEAL_STAGE = 'Lost' THEN 1
					ELSE 0
				END
			) + SUM(
				CASE
					WHEN DEAL_STAGE = 'Won' THEN 1
					ELSE 0
				END
			)
		)
	) AS WIN_RATE
FROM
	SALES_PIPELINE;

SELECT
	DEAL_STAGE,
	AVG(CLOSE_DATE::DATE - ENGAGE_DATE::DATE) AS DEAL_VELOCITY
FROM
	SALES_PIPELINE
WHERE
	DEAL_STAGE = 'Won'
GROUP BY
	DEAL_STAGE;

